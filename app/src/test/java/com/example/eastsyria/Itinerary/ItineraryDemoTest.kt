package com.example.eastsyria.Itinerary

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * A reproducible demo of the itinerary planner on the catalog snapshot: an Arabic request, the
 * same request in English, and an English request where a historically relevant castle is left
 * out by distance. Writes docs/rag/demo.md.
 */
class ItineraryDemoTest {

    private val catalog = ItineraryFixtures.catalog

    private val demos = listOf(
        "Arabic request (the user story)" to "بدي ٣ أماكن قريبة من دير الزور مرتبطة بتاريخ الفرات",
        "The same request in English" to "Suggest three places near Deir ez-Zor linked to the history of the Euphrates",
        "English request where a relevant castle is too far" to "Three medieval castles near Raqqa",
    )

    @Test
    fun demo() {
        val out = StringBuilder()
        out.append("# Itinerary planner: demo\n\n")
        out.append("Generated by `ItineraryDemoTest` from the catalog snapshot `${ItineraryFixtures.SNAPSHOT}`; the same code runs in the app's AI guide. ")
        out.append("Distances are straight lines (haversine); \"near\" means within ${ItineraryPlanner.DEFAULT_NEAR_RADIUS_KM.toInt()} km unless the request gives a radius. ")
        out.append("Every explanation is a sentence copied from the stop's own record, plus its own tags; `ItineraryCheck` verifies each one.\n\n")
        out.append("```bash\n./gradlew :app:testDebugUnitTest --tests \"com.example.eastsyria.Itinerary.ItineraryDemoTest\"\n```\n")

        val plans = demos.map { (title, query) ->
            val plan = ItineraryPlanner.plan(query, catalog) as ItineraryOutcome.Plan
            val checks = ItineraryCheck.verify(plan, catalog)
            val ar = plan.query.language == "ar"
            out.append("\n## $title\n\n> ${query}\n\n")
            out.append("- Language: ${plan.query.language}; asked for ${plan.requested}; concepts: ${plan.query.conceptIds.joinToString()}\n")
            out.append("- Start: ${plan.anchor?.name(plan.query.language)} (${plan.anchor?.source}); radius: ${plan.radiusKm?.toInt()} km${if (plan.radiusIsDefault) " (default)" else ""}\n")
            out.append("- **Suggested stop order** (straight-line; the app's map has no road routing, so no road routes or travel times are shown)\n\n")
            if (ar) out.append("<div dir=\"rtl\">\n\n")
            for (s in plan.stops) {
                val e = s.explanation
                val name = if (ar) s.landmark.nameArabic else s.landmark.name
                out.append("${s.number}. **$name** · ${ItineraryFixtures.km(s.fromAnchorKm)} from the start · leg ${ItineraryFixtures.km(s.legKm)}\n")
                out.append("   - «${e.quote?.text}» — `${e.quote?.field}`\n")
                if (e.matchedTags.isNotEmpty()) out.append("   - tags (`${e.tagField}`): ${e.matchedTags.joinToString("، ".takeIf { ar } ?: ", ")}\n")
                out.append("   - opens landmark `${s.landmark.id}`; source links: ${e.sourceLinks.ifEmpty { listOf("none in the record") }.joinToString()}\n")
                out.append("   - check: ${checks.first { it.landmarkId == s.landmark.id }.let { if (it.supported) "supported ✓" else "✗ ${it.problems}" }}\n")
            }
            if (ar) out.append("\n</div>\n")
            if (plan.stops.size < plan.requested.coerceAtMost(ItineraryPlanner.MAX_STOPS)) {
                out.append("\nOnly ${plan.stops.size} of ${plan.requested} requested places match within ${plan.radiusKm?.toInt()} km.\n")
            }
            if (plan.outsideRadius.isNotEmpty()) {
                out.append("\n**Relevant, but left out by distance:** ")
                out.append(plan.outsideRadius.joinToString { "${it.landmark.name} (${ItineraryFixtures.km(it.distanceKm)})" }).append("\n")
            }
            assertTrue(checks.all { it.supported })
            plan
        }

        // The Arabic and English requests find the same stops in the same order.
        assertEquals(plans[0].stops.map { it.landmark.id }, plans[1].stops.map { it.landmark.id })
        assertEquals(listOf("1", "6", "2"), plans[0].stops.map { it.landmark.id })
        // Mari is about the Euphrates but 110 km from Deir ez-Zor; Qalaat Najm is a medieval castle 100.4 km from Raqqa.
        assertTrue(plans[0].outsideRadius.any { it.landmark.id == "7" })
        assertTrue(plans[2].outsideRadius.any { it.landmark.id == "9" })

        ItineraryFixtures.reportFile("demo.md").writeText(out.toString())
        println(out)
    }
}
